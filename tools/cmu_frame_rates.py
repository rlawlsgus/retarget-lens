"""Build khumanoid/io/cmu_frame_rates.json: the true capture rate of CMU mocap trials.

The cgspeed BVH conversion of the CMU database rewrote every file's frame time to
1/120 s, but some subjects were captured at 60 Hz, so their BVHs play twice too
fast (143_11: 657 frames, 10.95 s real, 5.47 s in the BVH). AMASS keeps the C3D
header rate per trial (mocap_frame_rate); this script reads it from an AMASS CMU
folder and stores the rates of every subject that has any non-120 Hz trial.
Only frame rates are stored (metadata), no motion data.

    python tools/cmu_frame_rates.py data/raw/amass_cmu_smplx/CMU
"""

from __future__ import annotations

import argparse
import collections
import datetime as dt
import glob
import json
import os
import sys

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "khumanoid", "io", "cmu_frame_rates.json")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("amass_cmu", help="AMASS CMU folder (<subject>/<subject>_<trial>_stageii.npz)")
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args()

    rates: dict[str, dict[str, float]] = collections.defaultdict(dict)
    for p in sorted(glob.glob(os.path.join(args.amass_cmu, "*", "*_stageii.npz"))):
        trial = os.path.basename(p)[: -len("_stageii.npz")]
        subject = trial.split("_")[0]
        with np.load(p, allow_pickle=True) as d:
            rates[subject][trial] = float(d["mocap_frame_rate"])
    if not rates:
        print(f"no *_stageii.npz under {args.amass_cmu}")
        return 1
    keep = {s: t for s, t in rates.items() if any(r != 120.0 for r in t.values())}
    subjects = {}
    for s, trials in sorted(keep.items(), key=lambda kv: int(kv[0])):
        majority = collections.Counter(trials.values()).most_common(1)[0][0]
        subjects[str(int(s))] = {"majority_fps": majority, "trials": dict(sorted(trials.items()))}
    out = {
        "about": "True capture rate of CMU mocap trials whose subject has any non-120 Hz trial. "
                 "Every other CMU subject is 120 Hz, the rate the cgspeed BVH conversion assumes for all files.",
        "source": "AMASS CMU (SMPL-X N) mocap_frame_rate, i.e. the C3D header rate; generated by "
                  f"tools/cmu_frame_rates.py on {dt.date.today().isoformat()} from {sum(len(t) for t in rates.values())} trials",
        "subjects": subjects,
    }
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1)
    n60 = sum(1 for s in subjects.values() for r in s["trials"].values() if r != 120.0)
    print(f"wrote {args.out}: {len(subjects)} subjects, {n60} non-120 Hz trials")
    return 0


if __name__ == "__main__":
    sys.exit(main())
